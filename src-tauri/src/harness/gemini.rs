//! Gemini CLI's project layer (read once the folder is trusted): the command
//! rules in a policy file of Termo's own, `.gemini/termo-harness.toml`, which
//! `.gemini/settings.json` names in `policyPaths`; the checks as an
//! `AfterAgent` hook there, and AGENTS.md among the files it reads for
//! context. Protected paths go in the policy file too, as rules on its file
//! tools: a shell command can still reach them, as with Claude Code.
//!
//! Not `tools.exclude` and `tools.allowed`: Gemini CLI 0.63 turns an entry
//! like `run_shell_command(rm -rf)` there into a rule for a tool by that very
//! name, which no call has, and a command in `tools.allowed` denies every
//! other one. Nor `.gemini/policies/`: its workspace policies are switched
//! off. A file in `policyPaths` loads as the user's own policy, above
//! Gemini CLI's defaults and its approval modes.

use serde_json::{json, Map, Value};

use super::checks;
use super::instructions;
use super::model::{Access, Agent, Decision, Harness, Owned};

pub const FILE: &str = ".gemini/settings.json";
pub const POLICY_FILE: &str = ".gemini/termo-harness.toml";

const HEADER: &str = "# Generated by Termo from .termo/harness.json. Edit it in Termo's Harness panel: changes made here are overwritten.";

pub fn applies(spec: &Harness) -> bool {
    spec.targets(Agent::Gemini)
}

/// Gemini CLI's decision, the rule's priority (the higher, the earlier it's
/// weighed: a forbidden command wins over an allowed prefix of it) and the
/// modes it holds in.
fn rule(decision: Decision) -> (&'static str, u32, &'static str) {
    match decision {
        Decision::Deny => ("deny", 300, ""),
        Decision::Ask => ("ask_user", 200, ""),
        // Never in `plan`, the mode of an agent that may only look: allowed
        // here means "without asking", not "even there".
        Decision::Allow => ("allow", 100, "modes = [\"default\", \"autoEdit\", \"yolo\"]\n"),
    }
}

/// Gemini CLI's tools that write a file, and those that read one, each
/// taking it in `file_path` (`read_many_files` and `grep_search`, among
/// what they're given).
const EDIT_TOOLS: &[&str] = &["write_file", "replace"];
const READ_TOOLS: &[&str] = &["read_file", "read_many_files", "grep_search"];

/// A path pattern (`.env`, `src/gen/**`) as a regex over a tool call's
/// arguments, which a policy sees as JSON: a string that ends in the
/// pattern, after a folder separator (`/`, or `\` written `\\`) or nothing.
/// So `.env` is that name in any folder, and `src/gen/**` that folder
/// wherever the call names it from, absolute or relative.
///
/// No group is ever followed by a quantifier: Gemini CLI refuses any such
/// pattern as a possible ReDoS (and the whole file with it). Optional parts
/// are alternatives instead.
pub fn path_regex(pattern: &str) -> String {
    const SEP: &str = r"(?:/|\\\\)";
    const PART: &str = r#"[^"/\\]"#;
    // Anywhere already: a leading `**/` adds nothing.
    let mut rest = pattern.trim_start_matches('/');
    while let Some(after) = rest.strip_prefix("**/") {
        rest = after;
    }
    let mut body = String::new();
    let mut closed = false;
    while !rest.is_empty() {
        if let Some(after) = rest.strip_prefix("/**/") {
            // One separator, or a run of folders between two.
            body.push_str(&format!(r#"(?:/|\\\\|{SEP}[^"]*{SEP})"#));
            rest = after;
        } else if rest == "/**" {
            // The folder itself, or anything in it.
            body.push_str(&format!(r#"(?:"|{SEP}[^"]*")"#));
            closed = true;
            rest = "";
        } else if let Some(after) = rest.strip_prefix("**") {
            body.push_str(r#"[^"]*"#);
            rest = after;
        } else {
            let c = rest.chars().next().expect("not empty");
            match c {
                '*' => body.push_str(&format!("{PART}*")),
                '?' => body.push_str(PART),
                '/' => body.push_str(SEP),
                c if r"\.+()[]{}|^$".contains(c) => {
                    body.push('\\');
                    body.push(c);
                }
                c => body.push(c),
            }
            rest = &rest[c.len_utf8()..];
        }
    }
    // Right after the string opens, or after a separator.
    format!(r#"(?:"|/|\\\\){body}{}"#, if closed { "" } else { "\"" })
}

/// The policy file, all Termo's; `None` when there's no rule for it.
pub fn policy(spec: &Harness) -> Option<String> {
    if !applies(spec) || (spec.commands.is_empty() && spec.paths.is_empty()) {
        return None;
    }
    let mut out = format!("{HEADER}\n");
    for path in &spec.paths {
        let tools: Vec<&str> =
            if path.access == Access::NoRead { [EDIT_TOOLS, READ_TOOLS].concat() } else { EDIT_TOOLS.to_vec() };
        let tools = tools.iter().map(|tool| format!("\"{tool}\"")).collect::<Vec<_>>().join(", ");
        // TOML takes JSON's string literals as they are.
        let pattern = serde_json::to_string(&path_regex(&path.pattern)).unwrap_or_default();
        out.push_str(&format!(
            "\n[[rule]]\ntoolName = [{tools}]\nargsPattern = {pattern}\ndecision = \"deny\"\npriority = 300\ndenyMessage = \"Protected by this repository's harness.\"\n"
        ));
    }
    for command in &spec.commands {
        let (decision, priority, modes) = rule(command.decision);
        // TOML takes JSON's string literals as they are.
        let prefix = serde_json::to_string(command.prefix.trim()).unwrap_or_default();
        out.push_str(&format!(
            "\n[[rule]]\ntoolName = \"run_shell_command\"\ncommandPrefix = {prefix}\ndecision = \"{decision}\"\npriority = {priority}\n{modes}"
        ));
        if command.decision == Decision::Deny {
            out.push_str("denyMessage = \"Forbidden by this repository's harness.\"\n");
        }
    }
    Some(out)
}

pub fn desired(spec: &Harness, current: &Map<String, Value>) -> Owned {
    let mut owned = Owned::new();
    let mut push = |key: &str, value: Value| owned.entry(key.to_string()).or_default().push(value);
    if policy(spec).is_some() {
        // Relative: Gemini CLI reads it from the folder it runs in, the one
        // whose settings name it.
        push("policyPaths", json!(POLICY_FILE));
    }
    if !spec.checks.is_empty() {
        let command = checks::command(checks::Mode::ExitCode);
        // Gemini CLI's timeouts are in milliseconds.
        let timeout = u64::from(checks::timeout_sec(&spec.checks)) * 1000;
        push("hooks.AfterAgent", json!({ "hooks": [{ "type": "command", "command": command, "timeout": timeout }] }));
    }
    if instructions::agents_section(spec).is_some() {
        // Without the setting it reads GEMINI.md alone, so that one stays in
        // too; a list of the user's only gains AGENTS.md; a single name set
        // by them is theirs to change.
        match current.get("context").and_then(|context| context.get("fileName")) {
            None => {
                push("context.fileName", json!(instructions::AGENTS_MD));
                push("context.fileName", json!("GEMINI.md"));
            }
            Some(Value::Array(_)) => push("context.fileName", json!(instructions::AGENTS_MD)),
            Some(_) => {}
        }
    }
    owned
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::harness::json_merge;
    use crate::harness::model::{Check, CommandRule, PathRule};

    fn spec() -> Harness {
        Harness {
            commands: vec![
                CommandRule { prefix: "rm -rf".into(), decision: Decision::Deny },
                CommandRule { prefix: "git push".into(), decision: Decision::Ask },
                CommandRule { prefix: "npm test".into(), decision: Decision::Allow },
            ],
            checks: vec![Check { command: "npm test".into(), timeout_sec: Some(30) }],
            ..Harness::default()
        }
    }

    #[test]
    fn commands_go_to_the_policy_file_the_settings_name() {
        let owned = desired(&spec(), &Map::new());
        assert_eq!(owned["policyPaths"], vec![json!(POLICY_FILE)]);
        assert!(!owned.contains_key("tools.exclude") && !owned.contains_key("tools.allowed"));
        assert_eq!(owned["hooks.AfterAgent"][0]["hooks"][0]["timeout"], 30_000);
        assert_eq!(owned["context.fileName"], vec![json!("AGENTS.md"), json!("GEMINI.md")]);
    }

    #[test]
    fn each_command_is_a_shell_rule_of_its_decision() {
        let text = policy(&spec()).unwrap();
        let rules: Vec<&str> = text.split("[[rule]]").skip(1).collect();
        assert_eq!(rules.len(), 3);
        assert!(rules[0].contains("toolName = \"run_shell_command\"\ncommandPrefix = \"rm -rf\"\ndecision = \"deny\"\npriority = 300"));
        assert!(rules[0].contains("denyMessage"));
        assert!(rules[1].contains("commandPrefix = \"git push\"\ndecision = \"ask_user\"\npriority = 200"));
        // Allowed, but never for an agent in plan mode.
        assert!(rules[2].contains("decision = \"allow\"\npriority = 100\nmodes = [\"default\", \"autoEdit\", \"yolo\"]"));
        assert!(!rules[2].contains("plan"));
    }

    #[test]
    fn quotes_in_a_prefix_stay_inside_the_string() {
        let spec = Harness {
            commands: vec![CommandRule { prefix: "say \"hi\" \\ there".into(), decision: Decision::Deny }],
            ..Harness::default()
        };
        assert!(policy(&spec).unwrap().contains(r#"commandPrefix = "say \"hi\" \\ there""#));
    }

    #[test]
    fn no_command_rule_no_file() {
        let checks_only = Harness { checks: vec![Check { command: "make".into(), timeout_sec: None }], ..Harness::default() };
        assert_eq!(policy(&checks_only), None);
        assert!(!desired(&checks_only, &Map::new()).contains_key("policyPaths"));
        let not_for_gemini = Harness { agents: vec![Agent::Claude], ..spec() };
        assert_eq!(policy(&not_for_gemini), None);
    }

    #[test]
    fn path_patterns_as_regexes_over_the_arguments() {
        let sep = r"(?:/|\\\\)";
        let start = r#"(?:"|/|\\\\)"#;
        assert_eq!(path_regex(".env"), format!(r#"{start}\.env""#));
        assert_eq!(path_regex("src/gen/**"), format!(r#"{start}src{sep}gen(?:"|{sep}[^"]*")"#));
        assert_eq!(path_regex("**/*.pem"), format!(r#"{start}[^"/\\]*\.pem""#));
        assert_eq!(path_regex("a/**/b"), format!(r#"{start}a(?:/|\\\\|{sep}[^"]*{sep})b""#));
        assert_eq!(path_regex("/a+b?"), format!(r#"{start}a\+b[^"/\\]""#));
    }

    /// Gemini CLI's own test for a pattern it would refuse: a group, then a
    /// quantifier, after a group with one inside.
    #[test]
    fn no_pattern_has_a_quantified_group() {
        for pattern in [".env", "src/gen/**", "**/*.pem", "a/**/b/**", "x?y*z**w"] {
            let regex = path_regex(pattern);
            let groups_closed: Vec<usize> = regex.match_indices(')').map(|(at, _)| at).collect();
            for at in groups_closed {
                let next = regex[at + 1..].chars().next();
                assert!(!matches!(next, Some('*' | '+' | '?' | '{')), "{pattern}: {regex}");
            }
        }
    }

    #[test]
    fn protected_paths_are_rules_on_its_file_tools() {
        let spec = Harness {
            paths: vec![
                PathRule { pattern: ".env".into(), access: Access::NoRead },
                PathRule { pattern: "src/gen/**".into(), access: Access::NoEdit },
            ],
            ..Harness::default()
        };
        let text = policy(&spec).unwrap();
        let rules: Vec<&str> = text.split("[[rule]]").skip(1).collect();
        assert_eq!(rules.len(), 2);
        assert!(rules[0].contains(
            r#"toolName = ["write_file", "replace", "read_file", "read_many_files", "grep_search"]"#
        ));
        // The regex, in a TOML string: every backslash doubled.
        assert!(rules[0].contains(r#"argsPattern = "(?:\"|/|\\\\\\\\)\\.env\"""#), "{}", rules[0]);
        assert!(rules[1].contains(r#"toolName = ["write_file", "replace"]"#));
        assert!(rules.iter().all(|rule| rule.contains("decision = \"deny\"\npriority = 300")));
        // Paths alone are reason enough for the file.
        assert_eq!(desired(&spec, &Map::new())["policyPaths"], vec![json!(POLICY_FILE)]);
    }

    #[test]
    fn the_users_context_files_are_respected() {
        let list = json_merge::parse("s", Some(r#"{ "context": { "fileName": ["CONTEXT.md"] } }"#)).unwrap();
        assert_eq!(desired(&spec(), &list)["context.fileName"], vec![json!("AGENTS.md")]);
        let single = json_merge::parse("s", Some(r#"{ "context": { "fileName": "CONTEXT.md" } }"#)).unwrap();
        assert!(!desired(&spec(), &single).contains_key("context.fileName"));
    }
}
