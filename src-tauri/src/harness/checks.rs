//! The "done" gate: the repository's checks, run when an agent says it has
//! finished, sending it back to work when one fails.
//!
//! Every agent runs its hooks through a shell of its own choosing — bash,
//! sh, PowerShell (Claude Code falls back to it on Windows when it can't
//! find Git Bash) — so the hook itself only calls git, which is on every
//! PATH, and git runs the checks' script in its own sh through a one-off
//! alias. A shell alias runs at the repository's root and passes its exit
//! code on. The command is single-quoted, which bash and PowerShell read
//! alike.
//!
//! The script and the reason are read by the agents and live in the
//! repository, so they're in English whatever language Termo is in.

use super::model::{Check, Harness};

pub const SCRIPT_FILE: &str = ".termo/checks.sh";

/// For a check that doesn't say how long it may take.
pub const DEFAULT_TIMEOUT_SEC: u32 = 300;

/// How long the whole gate may take: every check, one after the other.
pub fn timeout_sec(checks: &[Check]) -> u32 {
    checks.iter().map(|check| check.timeout_sec.unwrap_or(DEFAULT_TIMEOUT_SEC)).sum()
}

/// How the gate tells the agent it isn't done.
#[derive(Clone, Copy)]
pub enum Mode {
    /// Exit code 2, with what the checks printed on stderr for the model
    /// (Claude Code, Codex, Gemini CLI).
    ExitCode,
    /// `{"decision":"block","reason":…}` on stdout (Copilot CLI's agentStop).
    Json,
}

/// The hook's command.
pub fn command(mode: Mode) -> String {
    let mode = match mode {
        Mode::ExitCode => "exit2",
        Mode::Json => "json",
    };
    format!("git -c 'alias.termo-checks=!sh {SCRIPT_FILE}' termo-checks {mode}")
}

/// Why the agent was sent back, when only a reason can be given.
pub fn reason(checks: &[Check]) -> String {
    let list = checks.iter().map(|check| format!("`{}`", check.command)).collect::<Vec<_>>().join(", ");
    format!("The repository's checks failed ({list}). Run them, fix what fails, and finish again.")
}

fn single_quoted(text: &str) -> String {
    format!("'{}'", text.replace('\'', r"'\''"))
}

/// The script, for a harness written for at least one agent.
pub fn script_for(spec: &Harness) -> Option<String> {
    if spec.agents.is_empty() {
        return None;
    }
    script(&spec.checks)
}

/// The script the hooks run; `None` with no checks.
pub fn script(checks: &[Check]) -> Option<String> {
    if checks.is_empty() {
        return None;
    }
    let chain = checks.iter().map(|check| format!("( {} )", check.command)).collect::<Vec<_>>().join(" && ");
    let block = serde_json::json!({ "decision": "block", "reason": reason(checks) }).to_string();
    Some(format!(
        "#!/bin/sh
# Generated by Termo from .termo/harness.json. Edit the checks in Termo's
# Harness panel: changes made here are overwritten.
#
# The agents' \"done\" hooks run this through git (git -c 'alias...'), so it
# runs in git's own sh at the repository's root, whatever shell the agent
# uses. \"exit2\": fail with exit code 2 and the output on stderr. \"json\":
# print a block decision on stdout instead.

# A turn that changed nothing (it only answered a question) isn't checked.
if git diff --quiet HEAD 2>/dev/null && [ -z \"$(git ls-files --others --exclude-standard)\" ]; then
  exit 0
fi

if [ \"$1\" = json ]; then
  {{ {chain}; }} >/dev/null 2>&1 && exit 0
  printf '%s\\n' {block}
  exit 0
fi

{{ {chain}; }} 1>&2 || exit 2
",
        block = single_quoted(&block),
    ))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn checks(commands: &[&str]) -> Vec<Check> {
        commands.iter().map(|command| Check { command: command.to_string(), timeout_sec: None }).collect()
    }

    #[test]
    fn no_checks_no_script() {
        assert_eq!(script(&[]), None);
    }

    #[test]
    fn checks_run_in_order() {
        let text = script(&checks(&["npm run check", "cargo test"])).unwrap();
        assert!(text.contains("{ ( npm run check ) && ( cargo test ); } 1>&2 || exit 2"));
    }

    #[test]
    fn the_command_reads_the_same_in_bash_and_powershell() {
        let command = command(Mode::Json);
        assert_eq!(command, "git -c 'alias.termo-checks=!sh .termo/checks.sh' termo-checks json");
        // Only single quotes: no escapes, no $ or backquote for either shell.
        assert!(!command.contains(['"', '$', '`']));
    }

    #[test]
    fn the_json_reason_survives_shell_quoting() {
        let text = script(&checks(&["echo 'hi'"])).unwrap();
        let line = text.lines().find(|line| line.trim_start().starts_with("printf")).unwrap();
        let quoted = line.trim_start().trim_start_matches("printf '%s\\n' ");
        // Undo POSIX single quoting: '...'\''...'.
        let unquoted = quoted.trim_matches('\'').replace(r"'\''", "'");
        let value: serde_json::Value = serde_json::from_str(&unquoted).unwrap();
        assert_eq!(value["decision"], "block");
        assert!(value["reason"].as_str().unwrap().contains("`echo 'hi'`"));
    }

    #[test]
    fn the_timeout_adds_up() {
        let mut list = checks(&["a", "b"]);
        list[0].timeout_sec = Some(60);
        assert_eq!(timeout_sec(&list), 60 + DEFAULT_TIMEOUT_SEC);
    }
}
