//! The "done" gate: the repository's checks, run when an agent says it has
//! finished, sending it back to work when one fails.
//!
//! Every agent runs its hooks through a shell of its own choosing — bash,
//! sh, PowerShell (Claude Code falls back to it on Windows when it can't
//! find Git Bash) — so the hook itself only calls git, which is on every
//! PATH, and git runs the checks' script in its own sh through a one-off
//! alias, which runs at the repository's root. The command is
//! single-quoted, which bash and PowerShell read alike.
//!
//! The gate answers with a decision on stdout, `{"decision":"block",
//! "reason":…}`, and exit code 0: every agent here reads it, and no shell in
//! between can change it. Exit code 2, the other way they all know, doesn't
//! survive Windows PowerShell, which Claude Code (without Git Bash), Codex
//! and Grok run hooks in: it turns it into 1, a failed hook they let through.
//!
//! The script and the reason are read by the agents and live in the
//! repository, so they're in English whatever language Termo is in.

use super::model::{Check, Harness};

pub const SCRIPT_FILE: &str = ".termo/checks.sh";

/// For a check that doesn't say how long it may take.
pub const DEFAULT_TIMEOUT_SEC: u32 = 300;

/// How long the whole gate may take: every check, one after the other.
pub fn timeout_sec(checks: &[Check]) -> u32 {
    checks.iter().map(|check| check.timeout_sec.unwrap_or(DEFAULT_TIMEOUT_SEC)).sum()
}

/// The hook's command, the same for every agent.
pub fn command() -> String {
    format!("git -c 'alias.termo-checks=!sh {SCRIPT_FILE}' termo-checks")
}

/// Why the agent was sent back, when only a reason can be given.
pub fn reason(checks: &[Check]) -> String {
    let list = checks.iter().map(|check| format!("`{}`", check.command)).collect::<Vec<_>>().join(", ");
    format!("The repository's checks failed ({list}). Run them, fix what fails, and finish again.")
}

fn single_quoted(text: &str) -> String {
    format!("'{}'", text.replace('\'', r"'\''"))
}

/// The script, for a harness written for at least one agent.
pub fn script_for(spec: &Harness) -> Option<String> {
    if spec.agents.is_empty() {
        return None;
    }
    script(&spec.checks)
}

/// The script the hooks run; `None` with no checks.
pub fn script(checks: &[Check]) -> Option<String> {
    if checks.is_empty() {
        return None;
    }
    let chain = checks.iter().map(|check| format!("( {} )", check.command)).collect::<Vec<_>>().join(" && ");
    // The decision up to where what the checks printed goes, still inside
    // the reason's string: the script closes it.
    let reason_text = format!("{}\n\nThe end of what they printed:\n", reason(checks));
    let quoted = serde_json::to_string(&reason_text).unwrap_or_default();
    let block = format!(r#"{{"decision":"block","reason":{}"#, quoted.trim_end_matches('"'));
    Some(format!(
        "#!/bin/sh
# Generated by Termo from .termo/harness.json. Edit the checks in Termo's
# Harness panel: changes made here are overwritten.
#
# The agents' \"done\" hooks run this through git (git -c 'alias...'), so it
# runs in git's own sh at the repository's root, whatever shell the agent
# uses. A failure is a block decision on stdout, with exit code 0, which no
# shell in between can change (PowerShell turns exit code 2 into 1).

# A turn that changed nothing (it only answered a question) isn't checked.
if git diff --quiet HEAD 2>/dev/null && [ -z \"$(git ls-files --others --exclude-standard)\" ]; then
  exit 0
fi

output=$({{ {chain}; }} 2>&1) && exit 0
# Its last lines, as a JSON string's inside: no control characters.
printf '%s' {block}
printf '%s\\n' \"$output\" | tail -n 60 | awk {escape}
printf '\"}}\\n'
",
        block = single_quoted(&block),
        escape = ESCAPE,
    ))
}

/// awk that writes each line inside a JSON string, ending in `\n`: a
/// backslash and a quote escaped, any other control character a space.
/// Character by character, so no awk's own escaping in `gsub` gets a say.
const ESCAPE: &str = r#"'{
    out = ""
    for (i = 1; i <= length($0); i++) {
      c = substr($0, i, 1)
      if (c == "\\") out = out "\\\\"
      else if (c == "\"") out = out "\\\""
      else if (c ~ /[[:cntrl:]]/) out = out " "
      else out = out c
    }
    printf "%s\\n", out
  }'"#;

#[cfg(test)]
mod tests {
    use super::*;

    fn checks(commands: &[&str]) -> Vec<Check> {
        commands.iter().map(|command| Check { command: command.to_string(), timeout_sec: None }).collect()
    }

    #[test]
    fn no_checks_no_script() {
        assert_eq!(script(&[]), None);
    }

    #[test]
    fn checks_run_in_order() {
        let text = script(&checks(&["npm run check", "cargo test"])).unwrap();
        assert!(text.contains("output=$({ ( npm run check ) && ( cargo test ); } 2>&1) && exit 0"));
        // No exit code but 0: the decision is on stdout.
        assert!(!text.contains("exit 2"));
    }

    #[test]
    fn the_command_reads_the_same_in_bash_and_powershell() {
        let command = command();
        assert_eq!(command, "git -c 'alias.termo-checks=!sh .termo/checks.sh' termo-checks");
        // Only single quotes: no escapes, no $ or backquote for either shell.
        assert!(!command.contains(['"', '$', '`']));
    }

    #[test]
    fn the_json_reason_survives_shell_quoting() {
        // Run for real, through the git that's here, as the hooks do.
        let Some(git) = crate::pty::bin_search::find_binary("git") else { return };
        let root = std::env::temp_dir().join(format!("termo-checks-test-{}", uuid::Uuid::new_v4()));
        std::fs::create_dir_all(root.join(".termo")).unwrap();
        let run = |args: &[&str]| std::process::Command::new(&git).args(args).current_dir(&root).output().unwrap();
        run(&["init", "-q"]);
        let failing = r#"echo 'it''s "quoted" \ back'; printf 'tab\there\033[31mred\n'; exit 1"#;
        std::fs::write(root.join(SCRIPT_FILE), script(&checks(&[failing])).unwrap()).unwrap();
        // Something changed, or nothing is checked.
        std::fs::write(root.join("new.txt"), "x").unwrap();

        let output = run(&["-c", &format!("alias.termo-checks=!sh {SCRIPT_FILE}"), "termo-checks"]);
        assert!(output.status.success());
        let value: serde_json::Value = serde_json::from_slice(&output.stdout).unwrap_or_else(|err| {
            panic!("{err}: {}", String::from_utf8_lossy(&output.stdout));
        });
        assert_eq!(value["decision"], "block");
        let reason = value["reason"].as_str().unwrap();
        let raw = String::from_utf8_lossy(&output.stdout);
        assert!(reason.contains("The repository's checks failed"), "{raw}");
        assert!(reason.contains("The end of what they printed"), "{raw}");
        assert!(reason.contains(r#"its "quoted" \ back"#), "{reason}");
        assert!(reason.contains("tab here [31mred"), "{reason}");

        // Passing: nothing said, and the turn ends.
        std::fs::write(root.join(SCRIPT_FILE), script(&checks(&["true"])).unwrap()).unwrap();
        let output = run(&["-c", &format!("alias.termo-checks=!sh {SCRIPT_FILE}"), "termo-checks"]);
        assert!(output.status.success() && output.stdout.is_empty());
        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn the_timeout_adds_up() {
        let mut list = checks(&["a", "b"]);
        list[0].timeout_sec = Some(60);
        assert_eq!(timeout_sec(&list), 60 + DEFAULT_TIMEOUT_SEC);
    }
}
