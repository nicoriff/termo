//! What the agents read as text: Termo's section of AGENTS.md (read by every
//! agent here, Gemini CLI once told to; see gemini.rs), with the free text
//! and every rule in words — an agent whose own files can't hold a rule
//! still hears of it — and, in a CLAUDE.md that doesn't import AGENTS.md
//! yet, a section that does. In English: it's read by the agents and lives
//! in the repository, whatever language Termo is in.

use super::markers;
use super::model::{Access, Agent, Decision, Harness};

pub const AGENTS_MD: &str = "AGENTS.md";
pub const CLAUDE_MD: &str = "CLAUDE.md";
pub const IMPORT: &str = "@AGENTS.md";
pub const GEMINI_MD: &str = "GEMINI.md";
pub const COPILOT_MD: &str = ".github/copilot-instructions.md";

/// The instruction files the agents read at a repository's root, as the
/// panel lists them and the unifying works on them.
pub const FILES: [&str; 4] = [AGENTS_MD, CLAUDE_MD, GEMINI_MD, COPILOT_MD];

const NOTE: &str = "<!-- Generated by Termo from .termo/harness.json. Edit it in Termo's Harness panel: changes made here are overwritten. -->";

/// The rules in words, one line each.
pub fn rule_lines(spec: &Harness) -> Vec<String> {
    let mut lines = Vec::new();
    for rule in &spec.paths {
        lines.push(match rule.access {
            Access::NoEdit => format!("- Don't modify `{}`.", rule.pattern),
            Access::NoRead => format!("- Don't read or modify `{}`.", rule.pattern),
        });
    }
    for rule in &spec.commands {
        match rule.decision {
            Decision::Deny => lines.push(format!("- Never run `{}`.", rule.prefix)),
            Decision::Ask => lines.push(format!("- Ask the user before running `{}`.", rule.prefix)),
            Decision::Allow => {}
        }
    }
    if !spec.checks.is_empty() {
        let list = spec.checks.iter().map(|check| format!("`{}`", check.command)).collect::<Vec<_>>().join(", ");
        lines.push(format!("- Before you finish a task, run {list} and fix whatever fails."));
    }
    lines
}

/// Termo's section of AGENTS.md; `None` when there's nothing to say.
pub fn agents_section(spec: &Harness) -> Option<String> {
    if spec.agents.is_empty() {
        return None;
    }
    let rules = rule_lines(spec);
    if rules.is_empty() && spec.instructions.is_empty() {
        return None;
    }
    let mut parts = vec![NOTE.to_string()];
    if !spec.instructions.is_empty() {
        parts.push(spec.instructions.clone());
    }
    if !rules.is_empty() {
        parts.push(format!("## Rules\n\n{}", rules.join("\n")));
    }
    Some(parts.join("\n\n"))
}

/// Whether a CLAUDE.md already brings AGENTS.md in, outside Termo's section.
fn imports_agents_md(text: &str) -> bool {
    let without = markers::replace(Some(text), None).unwrap_or_default();
    without.lines().any(|line| matches!(line.trim(), "@AGENTS.md" | "@./AGENTS.md"))
}

/// AGENTS.md's new text.
pub fn agents_md(spec: &Harness, before: Option<&str>) -> Option<String> {
    markers::replace(before, agents_section(spec).as_deref())
}

/// CLAUDE.md's new text. Claude Code reads AGENTS.md by itself only when
/// there's no CLAUDE.md, so one that exists gets the import; Termo never
/// creates one.
pub fn claude_md(spec: &Harness, before: Option<&str>) -> Option<String> {
    let before_text = before?;
    let wanted = spec.targets(Agent::Claude) && agents_section(spec).is_some() && !imports_agents_md(before_text);
    markers::replace(Some(before_text), wanted.then_some(IMPORT))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::harness::model::{Check, CommandRule, PathRule};

    fn spec() -> Harness {
        Harness {
            paths: vec![PathRule { pattern: ".env".into(), access: Access::NoRead }],
            commands: vec![
                CommandRule { prefix: "git push --force".into(), decision: Decision::Deny },
                CommandRule { prefix: "npm test".into(), decision: Decision::Allow },
            ],
            checks: vec![Check { command: "npm run check".into(), timeout_sec: None }],
            instructions: "Use pnpm.".into(),
            ..Harness::default()
        }
    }

    #[test]
    fn every_rule_but_allow_is_put_in_words() {
        let section = agents_section(&spec()).unwrap();
        assert!(section.contains("Use pnpm."));
        assert!(section.contains("- Don't read or modify `.env`."));
        assert!(section.contains("- Never run `git push --force`."));
        assert!(!section.contains("npm test"));
        assert!(section.contains("run `npm run check`"));
    }

    #[test]
    fn nothing_to_say_no_section() {
        assert_eq!(agents_section(&Harness::default()), None);
        assert_eq!(agents_md(&Harness::default(), None), None);
    }

    #[test]
    fn claude_md_gets_the_import_only_when_it_lacks_one() {
        let with = claude_md(&spec(), Some("# Project\n")).unwrap();
        assert!(with.contains(IMPORT));
        assert_eq!(claude_md(&spec(), Some("# Project\n@AGENTS.md\n")).unwrap(), "# Project\n@AGENTS.md\n");
        // Its own section doesn't count as the user's import.
        assert_eq!(claude_md(&spec(), Some(&with)).unwrap(), with);
        assert_eq!(claude_md(&spec(), None), None);
        let without_claude = Harness { agents: vec![Agent::Codex], ..spec() };
        assert_eq!(claude_md(&without_claude, Some(&with)).unwrap(), "# Project\n");
    }
}
