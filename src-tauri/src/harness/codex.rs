//! Codex's project layer, `.codex/`: command rules in a rules file of
//! Termo's own (Codex's `prefix_rule`s, its execution policy), and the
//! checks as a `Stop` hook in `.codex/hooks.json`. Codex reads either only
//! once the project is trusted. It has no rule for paths: those are a
//! `PreToolUse` hook there, the gate in guard.rs, which looks at its patches
//! and at the paths its shell commands name.

use serde_json::{json, Map, Value};

use super::checks;
use super::guard;
use super::model::{Agent, Decision, Harness, Owned};

pub const RULES_FILE: &str = ".codex/rules/termo-harness.rules";
pub const HOOKS_FILE: &str = ".codex/hooks.json";

const HEADER: &str = "# Generated by Termo from .termo/harness.json. Edit it in Termo's Harness panel: changes made here are overwritten.";

pub fn applies(spec: &Harness) -> bool {
    spec.targets(Agent::Codex)
}

fn decision(decision: Decision) -> &'static str {
    match decision {
        Decision::Deny => "forbidden",
        Decision::Ask => "prompt",
        Decision::Allow => "allow",
    }
}

fn justification(decision: Decision) -> &'static str {
    match decision {
        Decision::Deny => "Forbidden by this repository's harness.",
        Decision::Ask => "This repository's harness asks to check with the user first.",
        Decision::Allow => "Allowed by this repository's harness.",
    }
}

/// The rules file, all Termo's; `None` when there's no command rule.
pub fn rules(spec: &Harness) -> Option<String> {
    if !applies(spec) || spec.commands.is_empty() {
        return None;
    }
    let mut out = format!("{HEADER}\n\n");
    for rule in &spec.commands {
        // Starlark takes JSON's string literals as they are.
        let words: Vec<String> = rule
            .prefix
            .split_whitespace()
            .map(|word| serde_json::to_string(word).unwrap_or_default())
            .collect();
        out.push_str(&format!(
            "prefix_rule(pattern = [{}], decision = \"{}\", justification = \"{}\")\n",
            words.join(", "),
            decision(rule.decision),
            justification(rule.decision),
        ));
    }
    Some(out)
}

pub fn hooks(spec: &Harness, _current: &Map<String, Value>) -> Owned {
    let mut owned = Owned::new();
    if guard::for_codex(spec) {
        owned.insert(
            "hooks.PreToolUse".into(),
            vec![json!({ "hooks": [{ "type": "command", "command": guard::command(guard::Caller::Codex), "timeout": 30 }] })],
        );
    }
    if !spec.checks.is_empty() {
        let command = checks::command();
        owned.insert(
            "hooks.Stop".into(),
            vec![json!({ "hooks": [{ "type": "command", "command": command, "timeout": checks::timeout_sec(&spec.checks) }] })],
        );
    }
    owned
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::harness::model::{Check, CommandRule};

    #[test]
    fn commands_become_prefix_rules() {
        let spec = Harness {
            commands: vec![
                CommandRule { prefix: "git push --force".into(), decision: Decision::Deny },
                CommandRule { prefix: "say \"hi\"".into(), decision: Decision::Ask },
            ],
            ..Harness::default()
        };
        let text = rules(&spec).unwrap();
        assert!(text.contains(r#"prefix_rule(pattern = ["git", "push", "--force"], decision = "forbidden""#));
        assert!(text.contains(r#"pattern = ["say", "\"hi\""], decision = "prompt""#));
    }

    #[test]
    fn nothing_for_codex_no_file() {
        let spec = Harness {
            agents: vec![Agent::Claude],
            commands: vec![CommandRule { prefix: "x".into(), decision: Decision::Deny }],
            ..Harness::default()
        };
        assert_eq!(rules(&spec), None);
        assert_eq!(rules(&Harness::default()), None);
    }

    #[test]
    fn checks_become_a_stop_hook() {
        let spec = Harness { checks: vec![Check { command: "make test".into(), timeout_sec: None }], ..Harness::default() };
        let owned = hooks(&spec, &Map::new());
        assert_eq!(owned["hooks.Stop"][0]["hooks"][0]["command"], checks::command());
        assert!(!owned.contains_key("hooks.PreToolUse"));
    }

    #[test]
    fn paths_become_a_pre_tool_use_gate() {
        use crate::harness::model::{Access, PathRule};
        let spec = Harness { paths: vec![PathRule { pattern: ".env".into(), access: Access::NoRead }], ..Harness::default() };
        let owned = hooks(&spec, &Map::new());
        assert_eq!(owned["hooks.PreToolUse"][0]["hooks"][0]["command"], guard::command(guard::Caller::Codex));
    }
}
