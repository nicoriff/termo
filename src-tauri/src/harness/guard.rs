//! Copilot CLI's gate on each tool call: its repository `preToolUse` hook
//! (see copilot.rs) runs this script, which refuses a forbidden command or a
//! protected path, and asks first for a command that asks first. Copilot CLI
//! has no repository rule of its own for either.
//!
//! Like the checks (see checks.rs), the hook only calls git, which runs the
//! script in its own sh at the repository's root, so it needs nothing that
//! isn't on every machine with git: no jq, no node. The tool call comes as
//! JSON on stdin; the script reads the few strings it needs with sed.
//!
//! The script is read by the agents and lives in the repository, so it's in
//! English whatever language Termo is in.

use super::model::{Access, Decision, Harness};

pub const SCRIPT_FILE: &str = ".termo/copilot-guard.sh";

/// The hook's command: single-quoted, which bash and PowerShell read alike.
pub fn command() -> String {
    format!("git -c 'alias.termo-guard=!sh {SCRIPT_FILE}' termo-guard")
}

fn single_quoted(text: &str) -> String {
    format!("'{}'", text.replace('\'', r"'\''"))
}

/// A path pattern as `case` patterns, lowercased (the script lowercases the
/// path too, so `.ENV` on Windows is `.env`): the pattern from the root or
/// after any folder, a folder's `/**` also the folder itself. In `case`, `*`
/// crosses folders, so `**` is `*` too.
pub fn case_patterns(pattern: &str) -> Vec<String> {
    let mut pattern = pattern.trim_start_matches('/').to_lowercase();
    while let Some(rest) = pattern.strip_prefix("**/") {
        pattern = rest.to_string();
    }
    let pattern = pattern.replace("/**/", "/*").replace("**", "*");
    let glob = |text: &str| -> String {
        // Literal runs quoted, `*` and `?` left as globs.
        let mut out = String::new();
        let mut literal = String::new();
        for c in text.chars() {
            if c == '*' || c == '?' {
                if !literal.is_empty() {
                    out.push_str(&single_quoted(&literal));
                    literal.clear();
                }
                out.push(c);
            } else {
                literal.push(c);
            }
        }
        if !literal.is_empty() {
            out.push_str(&single_quoted(&literal));
        }
        out
    };
    let mut bases = vec![pattern.clone()];
    if let Some(folder) = pattern.strip_suffix("/*") {
        bases = vec![folder.to_string(), pattern.clone()];
    }
    bases.iter().flat_map(|base| [glob(base), format!("*/{}", glob(base))]).collect()
}

/// The script, for a harness with something for Copilot CLI to refuse or
/// ask about; `None` otherwise.
pub fn script_for(spec: &Harness) -> Option<String> {
    let commands: Vec<_> = spec.commands.iter().filter(|rule| rule.decision != Decision::Allow).collect();
    if !super::copilot::applies(spec) || (commands.is_empty() && spec.paths.is_empty()) {
        return None;
    }
    let tests = |decision: Decision| -> String {
        commands
            .iter()
            .filter(|rule| rule.decision == decision)
            .map(|rule| format!("  starts {} \"$1\" && return 0\n", single_quoted(&rule.prefix)))
            .collect()
    };
    let paths = |access: Option<Access>| -> String {
        spec.paths
            .iter()
            .filter(|rule| access.is_none_or(|access| rule.access == access))
            .map(|rule| format!("  case \"$1\" in {}) return 0 ;; esac\n", case_patterns(&rule.pattern).join("|")))
            .collect()
    };
    Some(
        SCRIPT
            .replace("{DENIED}", &tests(Decision::Deny))
            .replace("{ASKED}", &tests(Decision::Ask))
            .replace("{UNREADABLE}", &paths(Some(Access::NoRead)))
            .replace("{UNEDITABLE}", &paths(None)),
    )
}

const SCRIPT: &str = r#"#!/bin/sh
# Generated by Termo from .termo/harness.json. Edit the rules in Termo's
# Harness panel: changes made here are overwritten.
#
# Copilot CLI's preToolUse hook runs this through git (git -c 'alias...'),
# so it runs in git's own sh at the repository's root, whatever shell the
# agent uses. The tool call comes as JSON on stdin; a decision goes out as
# JSON on stdout, and nothing at all lets the call through.

input=$(cat | tr '\r\n' '  ')

# A string field of the call (its first), escapes undone. POSIX awk, sed
# and tr only: the same on Windows' git, Linux and macOS.
field() {
  printf '%s\n' "$input" | awk -v key="\"$1\"" '{
    i = index($0, key)
    if (!i) exit
    s = substr($0, i + length(key))
    sub(/^[ \t]*:[ \t]*/, "", s)
    if (substr(s, 1, 1) != "\"") exit
    out = ""
    for (j = 2; j <= length(s); j++) {
      c = substr(s, j, 1)
      if (c == "\\") {
        j++
        c = substr(s, j, 1)
        if (c == "n") c = "\n"
        else if (c == "t") c = "\t"
        else if (c == "r") c = ""
        else if (c == "u") { c = "?"; j += 4 }
      } else if (c == "\"") break
      out = out c
    }
    printf "%s\n", out
  }'
}

decide() {
  printf '{"permissionDecision":"%s","permissionDecisionReason":"%s"}\n' "$1" "$2"
  exit 0
}

# Whether command $2 is $1, or $1 followed by more.
starts() {
  case "$2" in "$1"|"$1 "*) return 0 ;; esac
  return 1
}

denied() {
{DENIED}  return 1
}

asked() {
{ASKED}  return 1
}

# $1: a path, slashes forward, lowercased.
unreadable() {
{UNREADABLE}  return 1
}

uneditable() {
{UNEDITABLE}  return 1
}

# A command, piece by piece: each part of a chain or a pipe on its own.
command=$(field command)
if [ -n "$command" ]; then
  pieces=$(printf '%s\n' "$command" | awk '{
    gsub(/&&|\|\||[;|]/, "\n")
    gsub(/[ \t]+/, " ")
    n = split($0, part, "\n")
    for (k = 1; k <= n; k++) { p = part[k]; sub(/^ /, "", p); sub(/ $/, "", p); print p }
  }')
  while IFS= read -r piece; do
    denied "$piece" && decide deny "Forbidden by this repository's harness."
  done <<EOF
$pieces
EOF
  while IFS= read -r piece; do
    asked "$piece" && decide ask "This repository's harness asks to check with the user first."
  done <<EOF
$pieces
EOF
fi

# Files: the call's path, or those a patch adds, changes, deletes or moves to.
tool=$(field toolName)
files=$( { field path; field toolArgs | sed -n -E 's/^\*\*\* (Add File|Update File|Delete File|Move to): *//p'; } \
  | tr '\\' '/' | tr 'A-Z' 'a-z')
while IFS= read -r file; do
  [ -n "$file" ] || continue
  case "$tool" in
    view|read|grep|glob) unreadable "$file" && decide deny "Protected by this repository's harness." ;;
    *) uneditable "$file" && decide deny "Protected by this repository's harness." ;;
  esac
done <<EOF
$files
EOF
exit 0
"#;

#[cfg(test)]
mod tests {
    use super::*;
    use crate::harness::model::{Agent, CommandRule, PathRule};

    #[test]
    fn patterns_from_the_root_or_any_folder() {
        assert_eq!(case_patterns(".env"), ["'.env'", "*/'.env'"]);
        assert_eq!(case_patterns("src/Gen/**"), ["'src/gen'", "*/'src/gen'", "'src/gen/'*", "*/'src/gen/'*"]);
        assert_eq!(case_patterns("**/*.pem"), ["*'.pem'", "*/*'.pem'"]);
        assert_eq!(case_patterns("it's"), [r"'it'\''s'", r"*/'it'\''s'"]);
    }

    #[test]
    fn nothing_to_refuse_no_script() {
        let allow_only = Harness {
            commands: vec![CommandRule { prefix: "npm test".into(), decision: Decision::Allow }],
            ..Harness::default()
        };
        assert_eq!(script_for(&allow_only), None);
        let not_copilot = Harness {
            agents: vec![Agent::Claude],
            paths: vec![PathRule { pattern: ".env".into(), access: Access::NoRead }],
            ..Harness::default()
        };
        assert_eq!(script_for(&not_copilot), None);
    }

    #[test]
    fn rules_land_in_their_functions() {
        let spec = Harness {
            commands: vec![
                CommandRule { prefix: "git push --force".into(), decision: Decision::Deny },
                CommandRule { prefix: "git push".into(), decision: Decision::Ask },
                CommandRule { prefix: "ls".into(), decision: Decision::Allow },
            ],
            paths: vec![
                PathRule { pattern: ".env".into(), access: Access::NoRead },
                PathRule { pattern: "dist/**".into(), access: Access::NoEdit },
            ],
            ..Harness::default()
        };
        let text = script_for(&spec).unwrap();
        let body = |name: &str| {
            let start = text.find(&format!("{name}() {{\n")).unwrap();
            let end = start + text[start..].find("\n}\n").unwrap();
            text[start..end].to_string()
        };
        assert!(body("denied").contains("starts 'git push --force' \"$1\" && return 0"));
        assert!(!body("denied").contains("'git push' "));
        assert!(body("asked").contains("starts 'git push' \"$1\""));
        assert!(!text.contains("'ls'"));
        assert!(body("unreadable").contains("'.env'|*/'.env'"));
        assert!(!body("unreadable").contains("dist"));
        // What can't be read can't be edited either.
        assert!(body("uneditable").contains("'.env'") && body("uneditable").contains("'dist/'*"));
    }

    #[test]
    fn the_command_reads_the_same_in_bash_and_powershell() {
        assert_eq!(command(), "git -c 'alias.termo-guard=!sh .termo/copilot-guard.sh' termo-guard");
        assert!(!command().contains(['"', '$', '`']));
    }
}
