//! The gate on each tool call, for the agents whose repository rules can't
//! say it by themselves: a `PreToolUse`-like hook runs this script, which
//! refuses a protected path, and for Copilot CLI also a forbidden command,
//! asking first for one that asks first.
//!
//! - Copilot CLI (`preToolUse` in `.github/hooks/`, see copilot.rs) has no
//!   repository rule for paths or commands.
//! - Codex (`PreToolUse` in `.codex/hooks.json`, see codex.rs) has its
//!   command rules (`.codex/rules/`), but none for paths; it reads and writes
//!   files mostly through its shell.
//!
//! Like the checks (see checks.rs), the hook only calls git, which runs the
//! script in its own sh at the repository's root, so it needs nothing that
//! isn't on every machine with git: no jq, no node. The tool call comes as
//! JSON on stdin; the script reads the few strings it needs with POSIX awk.
//!
//! The script is read by the agents and lives in the repository, so it's in
//! English whatever language Termo is in.

use super::model::{Access, Decision, Harness};

pub const SCRIPT_FILE: &str = ".termo/guard.sh";

/// Who runs the gate: how the call comes in and how the answer goes out.
#[derive(Clone, Copy)]
pub enum Caller {
    Copilot,
    Codex,
}

/// The hook's command: single-quoted, which bash and PowerShell read alike.
pub fn command(caller: Caller) -> String {
    let caller = match caller {
        Caller::Copilot => "copilot",
        Caller::Codex => "codex",
    };
    format!("git -c 'alias.termo-guard=!sh {SCRIPT_FILE}' termo-guard {caller}")
}

fn single_quoted(text: &str) -> String {
    format!("'{}'", text.replace('\'', r"'\''"))
}

/// A path pattern as `case` patterns, lowercased (the script lowercases the
/// path too, so `.ENV` on Windows is `.env`): the pattern from the root or
/// after any folder, a folder's `/**` also the folder itself. In `case`, `*`
/// crosses folders, so `**` is `*` too.
pub fn case_patterns(pattern: &str) -> Vec<String> {
    let mut pattern = pattern.trim_start_matches('/').to_lowercase();
    while let Some(rest) = pattern.strip_prefix("**/") {
        pattern = rest.to_string();
    }
    let pattern = pattern.replace("/**/", "/*").replace("**", "*");
    let glob = |text: &str| -> String {
        // Literal runs quoted, `*` and `?` left as globs.
        let mut out = String::new();
        let mut literal = String::new();
        for c in text.chars() {
            if c == '*' || c == '?' {
                if !literal.is_empty() {
                    out.push_str(&single_quoted(&literal));
                    literal.clear();
                }
                out.push(c);
            } else {
                literal.push(c);
            }
        }
        if !literal.is_empty() {
            out.push_str(&single_quoted(&literal));
        }
        out
    };
    let mut bases = vec![pattern.clone()];
    if let Some(folder) = pattern.strip_suffix("/*") {
        bases = vec![folder.to_string(), pattern.clone()];
    }
    bases.iter().flat_map(|base| [glob(base), format!("*/{}", glob(base))]).collect()
}

/// Whether Copilot CLI's hook runs the gate: something for it to refuse or
/// ask about.
pub fn for_copilot(spec: &Harness) -> bool {
    super::copilot::applies(spec)
        && (!spec.paths.is_empty() || spec.commands.iter().any(|rule| rule.decision != Decision::Allow))
}

/// Whether Codex's hook runs the gate: paths to protect (its commands have
/// rules of their own).
pub fn for_codex(spec: &Harness) -> bool {
    super::codex::applies(spec) && !spec.paths.is_empty()
}

/// The script, when some agent's hook runs it.
pub fn script_for(spec: &Harness) -> Option<String> {
    if !for_copilot(spec) && !for_codex(spec) {
        return None;
    }
    let tests = |decision: Decision| -> String {
        spec.commands
            .iter()
            .filter(|rule| rule.decision == decision)
            .map(|rule| format!("  starts {} \"$1\" && return 0\n", single_quoted(&rule.prefix)))
            .collect()
    };
    let paths = |access: Option<Access>| -> String {
        spec.paths
            .iter()
            .filter(|rule| access.is_none_or(|access| rule.access == access))
            .map(|rule| format!("  case \"$1\" in {}) return 0 ;; esac\n", case_patterns(&rule.pattern).join("|")))
            .collect()
    };
    Some(
        SCRIPT
            .replace("{DENIED}", &tests(Decision::Deny))
            .replace("{ASKED}", &tests(Decision::Ask))
            .replace("{UNREADABLE}", &paths(Some(Access::NoRead)))
            .replace("{UNEDITABLE}", &paths(None)),
    )
}

const SCRIPT: &str = r#"#!/bin/sh
# Generated by Termo from .termo/harness.json. Edit the rules in Termo's
# Harness panel: changes made here are overwritten.
#
# Copilot CLI's preToolUse hook and Codex's PreToolUse hook run this through
# git (git -c 'alias...'), so it runs in git's own sh at the repository's
# root, whatever shell the agent uses. $1 says which: the tool call comes as
# JSON on stdin in its shape, and a decision goes out on stdout in its shape;
# nothing at all lets the call through.

caller=${1:-copilot}
input=$(cat | tr '\r\n' '  ')

# A string field of the call (its first), escapes undone. POSIX awk, sed
# and tr only: the same on Windows' git, Linux and macOS.
field() {
  printf '%s\n' "$input" | awk -v key="\"$1\"" '{
    i = index($0, key)
    if (!i) exit
    s = substr($0, i + length(key))
    sub(/^[ \t]*:[ \t]*/, "", s)
    if (substr(s, 1, 1) != "\"") exit
    out = ""
    for (j = 2; j <= length(s); j++) {
      c = substr(s, j, 1)
      if (c == "\\") {
        j++
        c = substr(s, j, 1)
        if (c == "n") c = "\n"
        else if (c == "t") c = "\t"
        else if (c == "r") c = ""
        else if (c == "u") { c = "?"; j += 4 }
      } else if (c == "\"") break
      out = out c
    }
    printf "%s\n", out
  }'
}

decide() {
  if [ "$caller" = codex ]; then
    printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"%s","permissionDecisionReason":"%s"}}\n' "$1" "$2"
  else
    printf '{"permissionDecision":"%s","permissionDecisionReason":"%s"}\n' "$1" "$2"
  fi
  exit 0
}

protected() {
  decide deny "Protected by this repository's harness."
}

# Whether command $2 is $1, or $1 followed by more.
starts() {
  case "$2" in "$1"|"$1 "*) return 0 ;; esac
  return 1
}

denied() {
{DENIED}  return 1
}

asked() {
{ASKED}  return 1
}

# $1: a path, slashes forward, lowercased.
unreadable() {
{UNREADABLE}  return 1
}

uneditable() {
{UNEDITABLE}  return 1
}

# Paths as the script compares them, one per line.
normalized() {
  tr '\\' '/' | tr 'A-Z' 'a-z' | sed 's|^\./||'
}

# The files a patch adds, changes, deletes or moves to.
patched() {
  sed -n -E 's/^\*\*\* (Add File|Update File|Delete File|Move to): *//p'
}

tool=$(field toolName)
[ -n "$tool" ] || tool=$(field tool_name)
command=$(field command)

# A patch: the files it touches can't be protected.
if [ "$tool" = apply_patch ]; then
  files=$( { printf '%s\n' "$command"; field toolArgs; } | patched | normalized)
  while IFS= read -r file; do
    [ -n "$file" ] && uneditable "$file" && protected
  done <<EOF
$files
EOF
  exit 0
fi

if [ -n "$command" ]; then
  # Copilot CLI: its command rules, piece by piece, each part of a chain or
  # a pipe on its own. (Codex holds its own, in .codex/rules.)
  if [ "$caller" = copilot ]; then
    pieces=$(printf '%s\n' "$command" | awk '{
      gsub(/&&|\|\||[;|]/, "\n")
      gsub(/[ \t]+/, " ")
      n = split($0, part, "\n")
      for (k = 1; k <= n; k++) { p = part[k]; sub(/^ /, "", p); sub(/ $/, "", p); print p }
    }')
    while IFS= read -r piece; do
      denied "$piece" && decide deny "Forbidden by this repository's harness."
    done <<EOF
$pieces
EOF
    while IFS= read -r piece; do
      asked "$piece" && decide ask "This repository's harness asks to check with the user first."
    done <<EOF
$pieces
EOF
  fi

  # Paths named in the command: one that can't be read can't be named at
  # all; one that can't be edited, not by a command that writes.
  words=$(printf '%s\n' "$command" | tr ' \t"`;|&(){}=,<>' '\n\n\n\n\n\n\n\n\n\n\n\n\n' | tr -d "'" | normalized)
  lower=$(printf '%s' "$command" | tr 'A-Z' 'a-z')
  writes=no
  case "$lower" in
    *'>'*|*set-content*|*add-content*|*out-file*|*clear-content*|*new-item*|*remove-item*|*move-item*|*copy-item*|*rename-item*|*writealltext*|*writealllines*|*appendalltext*) writes=yes ;;
  esac
  for verb in rm mv cp tee touch truncate del erase ren rmdir 'sed -i' 'perl -i'; do
    case " $lower" in *[\ \;\|\&\(]"$verb "*) writes=yes ;; esac
  done
  while IFS= read -r word; do
    [ -n "$word" ] || continue
    unreadable "$word" && protected
    [ "$writes" = yes ] && uneditable "$word" && protected
  done <<EOF
$words
EOF
fi

# A file tool's own path (Copilot CLI's view, edit, create).
file=$(field path | normalized)
if [ -n "$file" ]; then
  case "$tool" in
    view|read|grep|glob) unreadable "$file" && protected ;;
    *) uneditable "$file" && protected ;;
  esac
fi
exit 0
"#;

#[cfg(test)]
mod tests {
    use super::*;
    use crate::harness::model::{Agent, CommandRule, PathRule};

    #[test]
    fn patterns_from_the_root_or_any_folder() {
        assert_eq!(case_patterns(".env"), ["'.env'", "*/'.env'"]);
        assert_eq!(case_patterns("src/Gen/**"), ["'src/gen'", "*/'src/gen'", "'src/gen/'*", "*/'src/gen/'*"]);
        assert_eq!(case_patterns("**/*.pem"), ["*'.pem'", "*/*'.pem'"]);
        assert_eq!(case_patterns("it's"), [r"'it'\''s'", r"*/'it'\''s'"]);
    }

    #[test]
    fn nothing_to_refuse_no_script() {
        let allow_only = Harness {
            commands: vec![CommandRule { prefix: "npm test".into(), decision: Decision::Allow }],
            ..Harness::default()
        };
        assert_eq!(script_for(&allow_only), None);
        let not_for_them = Harness {
            agents: vec![Agent::Claude],
            paths: vec![PathRule { pattern: ".env".into(), access: Access::NoRead }],
            ..Harness::default()
        };
        assert_eq!(script_for(&not_for_them), None);
        // Codex alone: only paths call for it.
        let codex_commands = Harness {
            agents: vec![Agent::Codex],
            commands: vec![CommandRule { prefix: "git push".into(), decision: Decision::Deny }],
            ..Harness::default()
        };
        assert_eq!(script_for(&codex_commands), None);
        let codex_paths = Harness { paths: not_for_them.paths.clone(), ..codex_commands };
        assert!(for_codex(&codex_paths) && !for_copilot(&codex_paths));
        assert!(script_for(&codex_paths).is_some());
    }

    #[test]
    fn rules_land_in_their_functions() {
        let spec = Harness {
            commands: vec![
                CommandRule { prefix: "git push --force".into(), decision: Decision::Deny },
                CommandRule { prefix: "git push".into(), decision: Decision::Ask },
                CommandRule { prefix: "ls".into(), decision: Decision::Allow },
            ],
            paths: vec![
                PathRule { pattern: ".env".into(), access: Access::NoRead },
                PathRule { pattern: "dist/**".into(), access: Access::NoEdit },
            ],
            ..Harness::default()
        };
        let text = script_for(&spec).unwrap();
        let body = |name: &str| {
            let start = text.find(&format!("{name}() {{\n")).unwrap();
            let end = start + text[start..].find("\n}\n").unwrap();
            text[start..end].to_string()
        };
        assert!(body("denied").contains("starts 'git push --force' \"$1\" && return 0"));
        assert!(!body("denied").contains("'git push' "));
        assert!(body("asked").contains("starts 'git push' \"$1\""));
        assert!(!text.contains("'ls'"));
        assert!(body("unreadable").contains("'.env'|*/'.env'"));
        assert!(!body("unreadable").contains("dist"));
        // What can't be read can't be edited either.
        assert!(body("uneditable").contains("'.env'") && body("uneditable").contains("'dist/'*"));
    }

    #[test]
    fn the_command_reads_the_same_in_bash_and_powershell() {
        assert_eq!(command(Caller::Codex), "git -c 'alias.termo-guard=!sh .termo/guard.sh' termo-guard codex");
        for caller in [Caller::Copilot, Caller::Codex] {
            assert!(!command(caller).contains(['"', '$', '`']));
        }
    }
}
